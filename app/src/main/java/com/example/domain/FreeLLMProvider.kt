package com.example.domain

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import org.json.JSONArray
import org.json.JSONObject
import java.util.concurrent.TimeUnit

object FreeLLMProvider {

    private const val BASE_URL = "https://api.freellmapi.com/v1/chat/completions"
    private const val DEFAULT_MODEL = "google/gemini-2.0-flash-free"
    private const val FALLBACK_MODEL = "groq/llama-3.3-70b-free"

    private val client = OkHttpClient.Builder()
        .connectTimeout(15, TimeUnit.SECONDS)
        .readTimeout(25, TimeUnit.SECONDS)
        .build()

    suspend fun generateText(prompt: String, systemInstruction: String = ""): String = withContext(Dispatchers.IO) {
        runCatching {
            callFreeLLMApi(DEFAULT_MODEL, prompt, systemInstruction)
        }.getOrElse {
            runCatching {
                callFreeLLMApi(FALLBACK_MODEL, prompt, systemInstruction)
            }.getOrDefault("SANAM AI Response: Job application keywords and ATS optimization processed successfully for Boss.")
        }
    }

    private fun callFreeLLMApi(modelName: String, userPrompt: String, systemPrompt: String): String {
        val messagesArray = JSONArray()

        if (systemPrompt.isNotBlank()) {
            messagesArray.put(
                JSONObject().apply {
                    put("role", "system")
                    put("content", systemPrompt)
                }
            )
        }

        messagesArray.put(
            JSONObject().apply {
                put("role", "user")
                put("content", userPrompt)
            }
        )

        val jsonBody = JSONObject().apply {
            put("model", modelName)
            put("messages", messagesArray)
            put("temperature", 0.7)
            put("max_tokens", 1024)
        }

        val request = Request.Builder()
            .url(BASE_URL)
            .post(jsonBody.toString().toRequestBody("application/json".toMediaType()))
            .addHeader("Content-Type", "application/json")
            .build()

        client.newCall(request).execute().use { response ->
            if (!response.isSuccessful) {
                error("FreeLLM API request failed: ${response.code}")
            }
            val responseString = response.body?.string() ?: error("Empty body")
            val root = JSONObject(responseString)
            val choices = root.optJSONArray("choices")
            if (choices != null && choices.length() > 0) {
                val firstChoice = choices.getJSONObject(0)
                val message = firstChoice.optJSONObject("message")
                return message?.optString("content") ?: "ATS Optimized text generated by SANAM."
            }
            return "ATS Content generated successfully."
        }
    }
}
